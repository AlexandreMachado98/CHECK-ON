// Chave de assinatura da versão de distribuição (opcional).
// No computador: arquivo keystore.properties nesta pasta (fora do Git).
// No GitHub Actions: variáveis CHECKON_KEYSTORE_FILE, CHECKON_KEYSTORE_PASSWORD, CHECKON_KEY_ALIAS e CHECKON_KEY_PASSWORD.
val keystoreProps = Properties().apply {
    val file = rootProject.file("keystore.properties")
    if (file.exists()) file.inputStream().use { load(it) }
}
fun signingValue(prop: String, env: String): String? =
    keystoreProps.getProperty(prop) ?: System.getenv(env)?.takeIf { it.isNotBlank() }

